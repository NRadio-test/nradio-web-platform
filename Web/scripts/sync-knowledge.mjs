import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { dataVersion, galaxyPosition, GALAXY_VERSION, validateKnowledgeEntries } from './galaxy-coordinates.mjs'

const scriptDir = dirname(fileURLToPath(import.meta.url))
const webDir = resolve(scriptDir, '..')
const sourcePath = resolve(webDir, '..', 'knowledge-base', 'import', 'knowledge.jsonl')
const publicOutput = resolve(webDir, 'frontend', 'public', 'data', 'knowledge.json')
const functionOutput = resolve(webDir, 'backend', 'functions', '_data', 'knowledge.js')
const astrbotOutput = resolve(webDir, '..', 'knowledge-base', 'astrbot-upload', 'NRadio-鲲鹏无限知识库.md')

const raw = await readFile(sourcePath, 'utf8')
const sourceEntries = raw
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line, index) => {
    try {
      return JSON.parse(line)
    } catch (error) {
      throw new Error(`knowledge.jsonl 第 ${index + 1} 行不是有效 JSON: ${error.message}`)
    }
  })

validateKnowledgeEntries(sourceEntries)
const entries = sourceEntries.map((entry) => ({
  ...entry,
  galaxy: galaxyPosition(entry)
}))

const verifiedAt = entries
  .map((entry) => entry.verified_at)
  .filter(Boolean)
  .sort()
  .at(-1) || '2026-07-30'
const reviewedAt = entries.map((entry) => entry.reviewed_at).filter(Boolean).sort().at(-1)

const payload = {
  meta: {
    name: 'NRadio 鲲鹏无限知识库',
    generated_at: `${verifiedAt}T00:00:00.000Z`,
    verified_at: verifiedAt,
    ...(reviewedAt ? { reviewed_at: reviewedAt } : {}),
    entry_count: entries.length,
    data_version: dataVersion(sourceEntries),
    galaxy_version: GALAXY_VERSION,
    notice: reviewedAt
      ? `知识内容已于 ${reviewedAt} 整理；资料日期与审阅日期不同，动态信息和冲突参数请按条目核对。`
      : '成员上传资料默认允许收录；动态内容按条目中的日期和适用条件理解。'
  },
  entries
}

await mkdir(dirname(publicOutput), { recursive: true })
await mkdir(dirname(functionOutput), { recursive: true })
await writeFile(publicOutput, `${JSON.stringify(payload, null, 2)}\n`, 'utf8')
await writeFile(
  functionOutput,
  `// Generated by scripts/sync-knowledge.mjs. Do not edit.\nexport const knowledgePayload = ${JSON.stringify(payload, null, 2)}\n`,
  'utf8'
)

const astrbotLines = [
  '# 鲲鹏无限 NRadio 知识库',
  '',
  `本文件由 \`knowledge-base/import/knowledge.jsonl\` 自动生成，共 ${entries.length} 条知识。每条内容都保留来源、上传者、核对日期和检索标签，适合直接上传到 AstrBot 知识库。`,
  '',
  '使用时应严格依据检索到的知识回答；资料没有提供的信息不要猜测。动态内容按条目中的日期、型号和适用条件理解。',
  '',
]

const reviewStatusLabels = {
  source_snapshot: '依据原资料整理，未声称当前外部重新核验',
  current_check_required: '动态信息，回答前核对当前渠道或政策',
  source_conflict: '资料参数冲突，确认批次或版本后回答'
}
let currentCategory = null

for (const entry of entries) {
  if (entry.category && entry.category !== currentCategory) {
    currentCategory = entry.category
    astrbotLines.push(`## ${currentCategory}`, '')
  }
  astrbotLines.push(
    `${entry.category ? '###' : '##'} ${entry.title}`,
    '',
    entry.text,
    '',
    `- InfoID：${entry.id}`,
    ...[...new Set([entry.source_url, ...(entry.source_urls || [])])].map((url) => `- 来源：${url}`),
    `- 上传者：${entry.uploaded_by}`,
    `- 原资料核对日期：${entry.verified_at}`,
    ...(entry.reviewed_at ? [`- 内容审阅日期：${entry.reviewed_at}`] : []),
    ...(entry.review_status ? [`- 审阅状态：${reviewStatusLabels[entry.review_status] || entry.review_status}`] : []),
    `- 标签：${entry.tags.join('、')}`,
    ''
  )
}

await mkdir(dirname(astrbotOutput), { recursive: true })
await writeFile(astrbotOutput, `${astrbotLines.join('\n').trim()}\n`, 'utf8')

console.log(`已同步 ${entries.length} 条知识到前端、Pages Functions 与 AstrBot 导入文件。`)
